#!/usr/bin/env bash
# KAN-860 (KAN-718 F7): the KAN-801 pre-image chain and proof, from TRACKED files only.
# LOCAL THROWAWAY POSTGRES ONLY. NEVER POINT THIS AT SUPABASE.
#
# Re-establishes the chain kan801_meetup_rsvp_attendee.sql names ("clean801.sh: events chain + D04 + D05 + seed781
# + harness801.sh pre-images"). clean801.sh, seed781.sql and harness801.sh were never committed and are lost; what
# survives is the judge's run log (Thebes review evidence agent/state/runtime/review-evidence/KAN-801/judge-83a2133a/
# clean801_run.log), which records what each step installed. This builder reproduces those steps:
#   1. supabase/tests/events_p4/base781_with_d04.sh: brand new cluster, the KAN-781 judge chain + D04 (k772_base781);
#   2. copy k801pre; 20261104110200 KAN-718 D05;
#   3. seed (replaces the lost seed781.sql; the ids are the ones kan719_z02_restore_test.sql and the KAN-781 clean
#      proof reference): game 78100000-..-0001 copied from game 71300000-..-0001 and meetup F 78100000-..-f001 copied
#      from meetup M 71300000-..-0101, both through the legacy path with event_id NULL (the KAN-711 mirror creates
#      their events parents, events.id = the row id), as kan718_d05_compat.sql seeds its own pair;
#   4. harness801 (replaces the lost harness801.sh): the three objects its log line names, VERBATIM from the
#      repository, none of which any tracked harness carries:
#        rpc_meetup_set_attendee(uuid,uuid,text)  baseline 20260829080500:13981-14010 + grants 20260915120000:746-747
#                                                 (the log pins md5(prosrc)=118f1db9..., asserted below)
#        meetup_attendees_pkey                    baseline 20260829080500:27420-27421 (the attendee upsert's arbiter)
#        _meetup_link_consume(uuid,uuid)          baseline 20260829080500:1217-1234
#   5. RED: the test on a copy of the pre-image (k801red) must FAIL (A* with 42703 m.owner_user_id);
#   6. GREEN: 20261104110600_kan801 applied on k801pre, then the test must PASS (TOTAL pass=25 fail=0).
#
# Usage (from the repository root):
#   bash supabase/tests/events_p4/build_kan801.sh /tmp/<new-datadir> <port>
# Stop and delete afterwards:
#   pg_ctl -D <datadir> stop -m fast && rm -rf <datadir> <datadir>.log <datadir>.fixtures
set -euo pipefail

DATADIR="${1:?usage: build_kan801.sh <new-datadir> <port>}"
PORT="${2:?usage: build_kan801.sh <new-datadir> <port>}"
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
M=supabase/migrations
B=$M/20260829080500_baseline_schema.sql
T=supabase/tests/events_p4/kan801_meetup_rsvp_attendee.sql

bash "$ROOT/supabase/tests/events_p4/base781_with_d04.sh" "$DATADIR" "$PORT"

FIX="$DATADIR.fixtures"
createdb -h /tmp -p "$PORT" -U postgres -T k772_base781 k801pre
DB=k801pre
psql_db() { psql -X -q -v ON_ERROR_STOP=1 -h /tmp -p "$PORT" -U postgres -d "$DB" "$@"; }
run() { echo "== [$DB] $1"; psql_db "${@:2}" -f "$ROOT/$1" >/dev/null; }

run $M/20261104110200_kan718_d05_old_client_compat_projection.sql

cat > "$FIX/seed801.sql" <<'SQL'
-- GENERATED by build_kan801.sh, LOCAL ONLY. Replaces the lost seed781.sql: one seeded game, one seeded meetup.
INSERT INTO public.games SELECT (jsonb_populate_record(NULL::public.games, to_jsonb(g) || jsonb_build_object(
    'id', '78100000-0000-0000-0000-000000000001', 'event_id', NULL, 'request_id', NULL, 'title', 'seed781 game'))).*
  FROM public.games g WHERE g.id = '71300000-0000-0000-0000-000000000001';
INSERT INTO public.meetups SELECT (jsonb_populate_record(NULL::public.meetups, to_jsonb(m) || jsonb_build_object(
    'id', '78100000-0000-0000-0000-00000000f001', 'event_id', NULL, 'request_id', NULL, 'title', 'seed781 meetup'))).*
  FROM public.meetups m WHERE m.id = '71300000-0000-0000-0000-000000000101';
SQL
echo "== [$DB] seed ($FIX/seed801.sql)"; psql_db -f "$FIX/seed801.sql" >/dev/null
echo "   $(psql_db -tA -c "SELECT 'seeded game ' || count(*) FILTER (WHERE e.event_type = 'game') || ' meetup ' || count(*) FILTER (WHERE e.event_type = 'meetup')
  FROM public.events e WHERE e.id IN ('78100000-0000-0000-0000-000000000001', '78100000-0000-0000-0000-00000000f001')")"

{ echo '-- GENERATED by build_kan801.sh, LOCAL ONLY. Replaces the lost harness801.sh; every statement VERBATIM.'
  echo "-- $B:13981-14010"; sed -n 13981,14010p "$ROOT/$B"
  echo "-- $M/20260915120000_meetups_hardening.sql:746-747"; sed -n 746,747p "$ROOT/$M/20260915120000_meetups_hardening.sql"
  echo "-- $B:27420-27421"; sed -n 27420,27421p "$ROOT/$B"
  echo "-- $B:1217-1234"; sed -n 1217,1234p "$ROOT/$B"; } > "$FIX/harness801.sql"
echo "== [$DB] harness801 pre-images ($FIX/harness801.sql)"; psql_db -f "$FIX/harness801.sql" >/dev/null
GOT=$(psql_db -tA -c "SELECT md5(prosrc) || ' secdef=' || prosecdef || ' config=' || proconfig::text || ' acl=' || proacl::text
  FROM pg_proc WHERE oid = 'public.rpc_meetup_set_attendee(uuid,uuid,text)'::regprocedure")
echo "   harness801: rpc_meetup_set_attendee md5(prosrc)=$GOT"
[ "$GOT" = '118f1db9bf66dff0d4a275c89b3703de secdef=true config={search_path=public} acl={postgres=X/postgres,authenticated=X/postgres,service_role=X/postgres}' ] \
  || { echo "build_kan801: rpc_meetup_set_attendee pre-image differs from the judged one (md5 118f1db9...)" >&2; exit 1; }
echo "   pre-images: $(psql_db -tA -c "SELECT string_agg(p.proname || '=' || left(md5(p.prosrc), 8), ' ' ORDER BY p.proname) FROM pg_proc p
  WHERE p.oid IN ('public.rpc_meetup_rsvp(uuid,text,uuid,uuid)'::regprocedure, 'public.can_current_user_rsvp_meetup(uuid,uuid)'::regprocedure,
                  'public.rpc_meetup_set_attendee(uuid,uuid,text)'::regprocedure)")"

createdb -h /tmp -p "$PORT" -U postgres -T k801pre k801red
echo "== RED [k801red] test on the pre-image (must FAIL)"
if OUT="$(psql -X -h /tmp -p "$PORT" -U postgres -d k801red -f "$ROOT/$T" 2>&1)"; then
  echo "$OUT"; echo "build_kan801: RED did not fail" >&2; exit 1
fi
echo "$OUT" | grep -E 'FAIL|TOTAL|ERROR'
echo "$OUT" | grep -q 'A1 FAIL expected=ret:void actual=42703:column m.owner_user_id does not exist' \
  || { echo "build_kan801: RED failed for another reason" >&2; exit 1; }

echo "== GREEN [$DB] 20261104110600_kan801 then the test"
run $M/20261104110600_kan801_d04_blockers_meetup_rsvp.sql
psql -X -v ON_ERROR_STOP=1 -h /tmp -p "$PORT" -U postgres -d k801pre -f "$ROOT/$T"
echo "build_kan801: PASS on port $PORT"
