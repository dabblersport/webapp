#!/usr/bin/env bash
# KAN-810 LOCAL CHAIN BUILD. LOCAL THROWAWAY POSTGRES ONLY. NEVER POINT THIS AT SUPABASE.
#
# Builds the chain the KAN-810 migration (20261104112000_kan810_cancel_game_idempotent.sql) applies on top of:
#   1. supabase/tests/events_p2/build_kan788.sh <datadir> <port>: a BRAND NEW cluster (it refuses an existing
#      datadir), harnesses + KAN-710..713 + KAN-714 B01..B14 in the decided order on database k788 (and k788b);
#   2. a copy of k788 named k772_kan810 (local_harness_kan772.sql refuses any database not named k772*), on which the
#      later Alpha-chain migrations that sort BEFORE 20261104112000 are applied in filename order:
#        20261104102000 KAN-716 realtime publication (publication supabase_realtime created empty first; it is
#                       platform-managed on Supabase, exactly as scripts/local_stack/apply_chain.sh does)
#        local_harness_kan772.sql, then 20261104110100 KAN-718 D04
#        20261104110200 KAN-718 D05, 20261104110300 KAN-718 D07, 20261104110400 KAN-785
#        rpc_meetup_rsvp pre-image (generated, VERBATIM: 20260912190747_kan180...sql:116-206 and
#                       20260915120000_meetups_hardening.sql:740-741 grants; no committed harness carries it),
#                       then 20261104110500 KAN-786
#   3. a copy of k772_kan810 named k810: the database the KAN-810 test and migration run on.
# 20261104110000 (KAN-713 location triggers) is already applied by step 1, right after KAN-713 access helpers.
#
# Usage (from the repository root):
#   bash supabase/tests/events_p4/build_kan810.sh /tmp/kan810_pg 54810
# Stop and delete afterwards:
#   pg_ctl -D /tmp/kan810_pg stop -m fast && rm -rf /tmp/kan810_pg /tmp/kan810_pg.log /tmp/kan810_pg.fixtures
set -euo pipefail

DATADIR="${1:?usage: build_kan810.sh <new-datadir> <port>}"
PORT="${2:?usage: build_kan810.sh <new-datadir> <port>}"
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
M=supabase/migrations

case "$DATADIR" in
  /tmp/*|/private/tmp/*) ;;
  *) echo "build_kan810: datadir must be under /tmp (throwaway cluster only)" >&2; exit 1 ;;
esac

bash "$ROOT/supabase/tests/events_p2/build_kan788.sh" "$DATADIR" "$PORT"

FIX="$DATADIR.fixtures"
ORDER2=(
  20261104102000_kan716_events_realtime_publication.sql
  20261104110100_kan718_d04_last_shared_field_reads.sql
  20261104110200_kan718_d05_old_client_compat_projection.sql
  20261104110300_kan718_d07_series_occurrence_unique.sql
  20261104110400_kan785_retire_rpc_meetup_my.sql
  20261104110500_kan786_meetup_leave.sql
)
# Full order (KAN-788 list + the above) through the apply-order check.
{ grep -v '^#' "$FIX/order.txt"; printf '%s\n' "${ORDER2[@]}"; } > "$FIX/order_kan810.txt"
echo "== order check (full KAN-810 chain)"
python3 "$ROOT/scripts/check_migration_apply_order.py" --order "$FIX/order_kan810.txt"

createdb -h /tmp -p "$PORT" -U postgres -T k788 k772_kan810
DB=k772_kan810
psql_db() { psql -X -q -v ON_ERROR_STOP=1 -h /tmp -p "$PORT" -U postgres -d "$DB" "$@"; }
run() { echo "== [$DB] $1"; psql_db "${@:2}" -f "$ROOT/$1"; }
NEXT=0
mig() {
  local want="${ORDER2[$NEXT]:-}"
  if [ "$1" != "$want" ]; then
    echo "build_kan810: step $1 is not ORDER2[$NEXT] ($want); refusing" >&2
    exit 1
  fi
  NEXT=$((NEXT + 1))
  run "$M/$1"
}

# The database must be a local throwaway: no Supabase roles or schemas.
psql_db -c "DO \$g\$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'supabase_admin')
     OR EXISTS (SELECT 1 FROM pg_namespace WHERE nspname IN ('storage', 'realtime', 'supabase_functions')) THEN
    RAISE EXCEPTION 'build_kan810: this looks like a Supabase database; refusing';
  END IF; END \$g\$;"

echo "== [$DB] CREATE PUBLICATION supabase_realtime (platform-managed on Supabase; created empty here)"
psql_db -c 'CREATE PUBLICATION supabase_realtime'
mig 20261104102000_kan716_events_realtime_publication.sql
run supabase/tests/events_p4/local_harness_kan772.sql
mig 20261104110100_kan718_d04_last_shared_field_reads.sql
mig 20261104110200_kan718_d05_old_client_compat_projection.sql
mig 20261104110300_kan718_d07_series_occurrence_unique.sql
mig 20261104110400_kan785_retire_rpc_meetup_my.sql
{
  echo '-- GENERATED by build_kan810.sh, LOCAL ONLY. VERBATIM rpc_meetup_rsvp pre-image for 20261104110500.'
  echo 'SET check_function_bodies = off;'
  sed -n 116,206p "$ROOT/$M/20260912190747_kan180_finding_b_meetup_rsvp_identity_and_profile_derivation.sql"
  sed -n 740,741p "$ROOT/$M/20260915120000_meetups_hardening.sql"
} > "$FIX/rsvp_preimage.sql"
echo "== [$DB] rpc_meetup_rsvp pre-image (generated, $FIX/rsvp_preimage.sql)"
psql_db -f "$FIX/rsvp_preimage.sql"
mig 20261104110500_kan786_meetup_leave.sql
[ "$NEXT" -eq "${#ORDER2[@]}" ] || { echo "build_kan810: applied $NEXT of ${#ORDER2[@]}" >&2; exit 1; }

createdb -h /tmp -p "$PORT" -U postgres -T k772_kan810 k810
echo "build_kan810: chain through 20261104110500 applied; test database k810 on port $PORT (socket /tmp)"
